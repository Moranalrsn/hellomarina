# ---------------------------------------------------------------- типограф
# Висячие предлоги, союзы и частицы привязываются к следующему слову неразрывным пробелом,
# тире — к предыдущему слову, как в макете Figma.
SHORT = ("а в во и к ко о об обо от ото с со у я до за из изо на над не ни но по под при про для без или как что это их его её мы вы он она они же ли бы "
         "a the to of in on at for and").split()
_short_re = re.compile(r"(?<![\w\-])(" + "|".join(sorted(SHORT, key=len, reverse=True)) + r") (?=\S)", re.I)
_dash_re = re.compile(r" (—|–)")
_num_re = re.compile(r"(\d) (?=[А-Яа-яA-Za-z%₽])")

def typograf_text(t):
    t = _dash_re.sub("\u00a0\\1", t)
    for _ in range(2):  # «и в клуб» — две короткие подряд
        t = _short_re.sub(lambda m: m.group(1) + "\u00a0", t)
    t = _num_re.sub("\\1\u00a0", t)
    return t

def typograf_html(doc):
    head, sep, body = doc.partition("<body>")
    if not sep:
        return doc
    out = re.sub(r">([^<>]+)<", lambda m: ">" + typograf_text(m.group(1)) + "<", body)
    return head + sep + out

def fix_newlines(s):
    # переносы строк внутри абзацев (**заголовок**\nтекст) -> <br>
    return s.replace("\n", "<br>")


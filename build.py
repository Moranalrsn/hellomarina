def esc(s):
    return html.escape(s, quote=False)

def rich(s):
    """**жирный** -> <strong>, остальное экранируется."""
    parts = re.split(r"\*\*(.+?)\*\*", s)
    return "".join(f"<strong>{esc(p)}</strong>" if i % 2 else esc(p) for i, p in enumerate(parts))


# ------------------------------------------------------------------ CASE HELPERS
def P(*paras):
    return '<div class="prose">' + "".join(f"<p>{rich(p)}</p>" for p in paras) + "</div>"

def fig(src, alt, w, h, scroll=False):
    i = img(src, alt, w, h)
    if scroll:
        return f'<figure class="figure"><div class="scroll-x" tabindex="0" role="region" aria-label="{html.escape(alt)}">{i}</div><figcaption class="scroll-hint">Листайте вбок →</figcaption></figure>'
    return f'<figure class="figure">{i}</figure>'

def section(title, *body, sub=False):
    tag = '<h3 class="h3">' if sub else '<h2 class="h2">'
    close = "</h3>" if sub else "</h2>"
    cls = "block-sm" if sub else "block"
    return f'<section class="{cls}">{tag}{esc(title)}{close}{"".join(body)}</section>'

def bare(*body, cls="block-sm"):
    return f'<div class="{cls}">{"".join(body)}</div>'

def cards2(items, story=False):
    out = []
    for it in items:
        if story:
            out.append(f'<div class="card story"><p class="card-text">{rich(it)}</p></div>')
        else:
            t, d = it
            out.append(f'<div class="card"><h4 class="card-title">{esc(t)}</h4><p class="card-text">{rich(d)}</p></div>')
    return f'<div class="cards-2">{"".join(out)}</div>'

